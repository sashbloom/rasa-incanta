def find_won_deals_by_account_ids(account_ids: list[int]) -> list[dict]:
    """Practus-history classification (§1): `stage = 'Client Won'` deals for
    this company's account(s)."""
    if not account_ids:
        return []
    with get_connection() as conn, conn.cursor() as cur:
        cur.execute(
            "SELECT id, account_id, deal_name, stage, services, industry_type, "
            "date_converted_to_client FROM deals "
            "WHERE account_id = ANY(%s) AND stage = 'Client Won'",
            (account_ids,),
        )
        return cur.fetchall()


def find_won_deals_by_industry(industry: str) -> list[dict]:
    """P1 (icp-skill.md STEP 3): "5+ confirmed clients in the industry"
    counts confirmed Practus clients across the WHOLE CRM, not just this
    one account's own deals -- a case-insensitive exact match on
    `industry_type`, since that field is a BD-picked category label, not
    free text to fuzzy-search."""
    if not industry:
        return []
    with get_connection() as conn, conn.cursor() as cur:
        cur.execute(
            "SELECT d.id, d.account_id, a.account_name, d.deal_name, d.industry_type "
            "FROM deals d JOIN accounts a ON a.id = d.account_id "
            "WHERE d.stage = 'Client Won' AND lower(d.industry_type) = lower(%s)",
            (industry,),
        )
        return cur.fetchall()


def find_all_won_deals() -> list[dict]:
    """Every Client Won deal across the whole CRM, industry_type included --
    unlike find_won_deals_by_industry(), not scoped to one target industry.
    Feeds P1's broader "confirmed clients by industry" breakdown
    (practus_history.confirmed_client_industry_breakdown()), which lets the
    narrative honestly describe adjacent-industry breadth even when the
    exact target industry has zero confirmed clients."""
    with get_connection() as conn, conn.cursor() as cur:
        cur.execute(
            "SELECT d.id, d.account_id, a.account_name, d.industry_type "
            "FROM deals d JOIN accounts a ON a.id = d.account_id "
            "WHERE d.stage = 'Client Won'"
        )
        return cur.fetchall()


