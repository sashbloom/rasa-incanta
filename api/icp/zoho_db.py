def find_user_by_name_fragment(name: str, limit: int = 10) -> list[dict]:
    """EP/EL/TL name lookups (P3 team-fielded checks) against `users`."""
    if not name or not name.strip():
        return []
    with get_connection() as conn, conn.cursor() as cur:
        cur.execute(
            "SELECT id, full_name, email, role_name, profile_name, sbu, team, status "
            "FROM users WHERE full_name ILIKE %s AND status = 'Active' LIMIT %s",
            (f"%{name.strip()}%", limit),
        )
        return cur.fetchall()


